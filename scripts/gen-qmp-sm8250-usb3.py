#!/usr/bin/env python3
"""Write drivers/QcomXnuUsbDebug/soc/Sm8250QmpUsb3.h: the SM8250 QMP USB3/DP combo PHY (usb_1_qmpphy, 0x088e8000), USB side, from the
mainline Linux tables. The counterpart of UniXNU-sheng's gen-qmp-usb3-table.py (SM8550); only the table selection differs:
sm8250_usb3dpphy_cfg in phy-qcom-qmp-combo.c takes sm8150_usb3_serdes_tbl, sm8250_usb3_{tx,rx,pcs,pcs_usb}_tbl, qmp_combo_offsets_v3
and the V4/V5 PCS register layout (qmp_v45_usb3phy_regs_layout, pcs_usb at pcs + 0x300).

usage: gen-qmp-sm8250-usb3.py LINUX_TREE [OUTPUT]
  LINUX_TREE needs drivers/phy/qualcomm (a sparse checkout of that directory is enough).
"""
import glob
import re
import subprocess
import sys
from pathlib import Path

root = sys.argv[1]
out = Path(sys.argv[2]) if len(sys.argv) > 2 else \
    Path(__file__).resolve().parents[1] / 'drivers/QcomXnuUsbDebug/soc/Sm8250QmpUsb3.h'
q = root + '/drivers/phy/qualcomm/'
defs = {}
for path in sorted(glob.glob(q + 'phy-qcom-qmp*.h')) + [q + 'phy-qcom-qmp-combo.c']:
    for m in re.finditer(r'^#define\s+(\w+)\s+(0x[0-9a-fA-F]+|\d+)\s*$', open(path).read(), re.M):
        defs.setdefault(m[1], int(m[2], 0))
src = open(q + 'phy-qcom-qmp-combo.c').read()

cfg = re.search(r'static const struct qmp_phy_cfg sm8250_usb3dpphy_cfg = \{(.*?)\n\};', src, re.S)[1]
pick = {k: re.search(r'\.' + k + r'\s*=\s*&?(\w+)', cfg)[1] for k in
        ('offsets', 'serdes_tbl', 'tx_tbl', 'rx_tbl', 'pcs_tbl', 'pcs_usb_tbl', 'regs')}
assert pick['offsets'] == 'qmp_combo_offsets_v3', pick
assert pick['regs'] == 'qmp_v45_usb3phy_regs_layout', pick


def table(name):
    body = re.search(r'static const struct qmp_phy_init_tbl ' + name + r'\[\] = \{(.*?)\n\};', src, re.S)[1]
    rows = []
    for m in re.finditer(r'QMP_PHY_INIT_CFG(_LANE)?\((\w+),\s*(0x[0-9a-fA-F]+|\d+)(?:,\s*(\w+))?\)', body):
        lane = int(m[4]) if m[1] else 0
        rows.append((defs[m[2]], int(m[3], 0), lane))
    return rows


body = re.search(r'static const struct qmp_combo_offsets qmp_combo_offsets_v3 = \{(.*?)\n\};', src, re.S)[1]
OFF = {k: int(v, 16) for k, v in re.findall(r'\.(\w+)\s*=\s*(0x[0-9a-fA-F]+)', body)}
rows = [(OFF['usb3_serdes'] + r, v) for r, v, _ in table(pick['serdes_tbl'])]
for name, a, b in ((pick['tx_tbl'], 'txa', 'txb'), (pick['rx_tbl'], 'rxa', 'rxb')):
    tbl = table(name)
    rows += [(OFF[a] + r, v) for r, v, lane in tbl if lane in (0, 1)]
    rows += [(OFF[b] + r, v) for r, v, lane in tbl if lane in (0, 2)]
rows += [(OFF['usb3_pcs'] + r, v) for r, v, _ in table(pick['pcs_tbl'])]
rows += [(OFF['usb3_pcs_usb'] + r, v) for r, v, _ in table(pick['pcs_usb_tbl'])]

body = re.search(r'static const unsigned int qmp_v45_usb3phy_regs_layout\[QPHY_LAYOUT_SIZE\] = \{(.*?)\n\};', src, re.S)[1]
layout = dict(re.findall(r'\[(QPHY_\w+)\]\s*=\s*(\w+)', body))
pcs = {n: OFF['usb3_pcs'] + defs[layout[k]] for n, k in
       (('Reset', 'QPHY_SW_RESET'), ('Start', 'QPHY_START_CTRL'), ('Status', 'QPHY_PCS_STATUS'),
        ('PowerDown', 'QPHY_PCS_POWER_DOWN_CONTROL'))}
com = {n: OFF['com'] + defs[v] for n, v in
       (('ComMode', 'QPHY_V3_DP_COM_PHY_MODE_CTRL'), ('ComReset', 'QPHY_V3_DP_COM_SW_RESET'),
        ('ComPower', 'QPHY_V3_DP_COM_POWER_DOWN_CTRL'), ('ComSwi', 'QPHY_V3_DP_COM_SWI_CTRL'),
        ('ComTypec', 'QPHY_V3_DP_COM_TYPEC_CTRL'), ('ComResetOvrd', 'QPHY_V3_DP_COM_RESET_OVRD_CTRL'))}
try:
    rev = subprocess.run(['git', '-C', root, 'log', '-1', '--format=%h'], capture_output=True, text=True).stdout.strip()
except OSError:
    rev = ''
text = ('/* SPDX-License-Identifier: GPL-2.0-only\n * SM8250 QMP USB3/DP combo PHY (0x088e8000), USB side. Generated by '
        'UniXNU-gts7xlwifi scripts/gen-qmp-sm8250-usb3.py\n * from Linux ' + (rev + ' ' if rev else '') +
        'drivers/phy/qualcomm/phy-qcom-qmp-combo.c sm8250_usb3dpphy_cfg (register values only). */\n'
        '#ifndef QUD_SM8250_QMP_USB3_H\n#define QUD_SM8250_QMP_USB3_H\n#include <stdint.h>\n')
text += 'enum {' + ', '.join(f'kQmp{n} = {v:#x}' for n, v in list(pcs.items()) + list(com.items())) + '};\n'
text += 'static const struct {uint16_t offset; uint8_t value;} kQmpUsb3Init[] = {\n'
text += ''.join(f' {{{r:#x}, {v:#x}}},\n' for r, v in rows) + '};\n#endif\n'
out.write_text(text)
print(len(rows), 'writes', {k: hex(v) for k, v in pcs.items()}, {k: hex(v) for k, v in com.items()}, '->', out)
