"""Generate package/GpuFirmwareA650.c from this tablet's own A650 firmware (not redistributed).

Inputs in .cache/firmware/gpu (pull them from your SM-T970 once, e.g. from TWRP):
  a650_gmu.bin, a650_sqe.fw   /vendor/firmware/
  a650_zap.elf                reassembled from firmware_mnt/image/a650_zap.mdt + .b0N by their program headers
                              (this script does that when only the .mdt/.b0N split is present).
Usage: python3 scripts/gen-gpu-firmware-a650.py [--check]
"""
import hashlib, struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FW = ROOT / '.cache/firmware/gpu'
OUT = ROOT / 'package/GpuFirmwareA650.c'


def zap_elf():
    elf = FW / 'a650_zap.elf'
    if elf.is_file():
        return elf.read_bytes()
    mdt = (FW / 'a650_zap.mdt').read_bytes()
    if mdt[:4] != b'\x7fELF' or mdt[4] != 1:
        raise SystemExit('a650_zap.mdt is not an ELF32 header')
    phoff, phentsize, phnum = struct.unpack_from('<I', mdt, 28)[0], *struct.unpack_from('<HH', mdt, 42)
    phdrs = [struct.unpack_from('<8I', mdt, phoff + i * phentsize) for i in range(phnum)]
    # Each segment (b00 holds the ELF and program headers) at its file offset; the .mdt itself also carries the hash segment.
    image = bytearray(max(p[1] + p[4] for p in phdrs))
    for i, p in enumerate(phdrs):
        part = FW / f'a650_zap.b{i:02d}'
        if p[4] and part.is_file():
            data = part.read_bytes()[:p[4]]
            image[p[1]:p[1] + len(data)] = data
    return bytes(image)


def array(name, label, data):
    rows = [','.join(str(b) for b in data[i:i + 24]) + ',' for i in range(0, len(data), 24)]
    return (f'// {label}: {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()}\n'
            f'const uint8_t native_gpu_{name}_firmware[] = {{\n' + '\n'.join(rows) + '\n};\n'
            f'const uint32_t native_gpu_{name}_firmware_size = {len(data)};\n')


text = ('// The A650 firmware, compiled in (gts7xlwifi). Generated by scripts/gen-gpu-firmware-a650.py from the vendor images\n'
        '// read from the tablet (.cache/firmware/gpu): a650_gmu.bin and a650_sqe.fw from /vendor/firmware\n'
        "// (byte-identical to alioth's), a650_zap.elf reassembled from the Samsung-signed a650_zap.mdt/.b01/.b02 of\n"
        '// firmware_mnt/image by their program headers. These symbols are what package/GpuProbe.cpp weak-imports. Regenerate, do not edit.\n'
        '#include <stdint.h>\n'
        + array('gmu', 'a650_gmu.bin', (FW / 'a650_gmu.bin').read_bytes())
        + array('sqe', 'a650_sqe.fw', (FW / 'a650_sqe.fw').read_bytes())
        + array('zap', 'a650_zap.elf', zap_elf()))
if '--check' in sys.argv:
    sys.exit(0 if OUT.is_file() and OUT.read_text() == text else 1)
OUT.write_text(text)
print(f'wrote {OUT.relative_to(ROOT)}')
